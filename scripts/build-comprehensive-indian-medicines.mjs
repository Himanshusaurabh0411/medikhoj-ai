// Function to calculate GS1 Luhn mod-10 check-digit
function calculateLuhnCheckDigit(digitsWithoutCheck) {
  const digits = digitsWithoutCheck.replace(/[^0-9]/g, "");
  let sum = 0;
  for (let i = digits.length - 1; i >= 0; i--) {
    const n = parseInt(digits[i], 10);
    const weight = ((digits.length - i) % 2 === 1) ? 3 : 1;
    sum += n * weight;
  }
  return (10 - (sum % 10)) % 10;
}

function makeValidBarcode(base12) {
  const base = String(base12).padStart(12, "8").slice(0, 12);
  const check = calculateLuhnCheckDigit(base);
  const barcode = `${base}${check}`;
  const gtin = `0${barcode}`;
  return { barcode, gtin };
}

